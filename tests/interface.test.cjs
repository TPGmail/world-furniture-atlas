const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const read = pathName => fs.readFileSync(path.join(__dirname, '..', pathName), 'utf8');
const html = read('site/index.html');
const css = read('site/interface.css');
const js = read('site/interface.js');
assert.ok(html.includes('href="interface.css"'), 'Interface stylesheet must be loaded');
assert.ok(html.includes('src="interface.js"'), 'Interface script must be loaded');
assert.ok(html.indexOf('World Wood &amp; Furniture Atlas</h1>') < html.indexOf('Sao lưu và khôi phục JSON'), 'Backup tools belong after branding');
assert.ok(html.indexOf('Đồng bộ Google Drive T.MN') < html.indexOf('Sao lưu và khôi phục JSON'), 'Keep backup near cloud settings');
assert.ok(html.includes('id="customer-directory-toggle"'), 'Customer list needs a toggle');
assert.ok(html.includes('id="customer-directory-body"'), 'Customer list needs toggleable body');
assert.ok(html.includes('id="header-sync-status"'), 'Cloud status remains visible');
assert.equal((html.match(/<div\b/g) || []).length, (html.match(/<\/div>/g) || []).length, 'Balanced div tags');
assert.equal((html.match(/<details\b/g) || []).length, (html.match(/<\/details>/g) || []).length, 'Balanced details tags');
assert.ok(css.includes('@media (max-width: 900px)'), 'Mobile layout rules required');
assert.ok(css.includes('.customer-osm-controls.is-collapsed'), 'Collapsed map list styles required');
assert.ok(css.includes('min-height: 44px'), 'Touch target sizing required');
new vm.Script(js, { filename: 'interface.js' });
console.log('Interface UX structural checks passed.');
